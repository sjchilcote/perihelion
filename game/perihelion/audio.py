"""pygame.mixer sound bank + graph-propagated positional audio.

Sounds are loaded lazily from game/assets/sfx/*.wav. A missing wav logs once
to stderr and is skipped -- the sound bank is generated by a parallel tool
(tools/soundgen) and may be partial; the game must still run silently for
whatever hasn't landed yet.
"""

from __future__ import annotations

import sys
from pathlib import Path

import pygame

import necore

SFX_DIR = Path(__file__).resolve().parents[1] / "assets" / "sfx"

# Sound level falls off one "stop" per portal hop away from the player, per
# the level design's audio-before-visibility horror pacing (ENGINE_DESIGN
# §3.4 / research_design.md #15).
HOP_ATTENUATION = 0.55


class Audio:
    def __init__(self, mute: bool = False):
        self.master_vol = 1.0
        self.sfx_vol = 1.0
        self.ambience_vol = 0.35
        self.muted = mute
        # optional recorder callback (kind, name, vol, pan); fires even when
        # muted or the mixer failed, so headless captures still log audio
        self.tap = None

        self._sounds: dict[str, "pygame.mixer.Sound | None"] = {}
        self._missing_logged: set[str] = set()

        self._ambience_name: str | None = None
        self._ambience_channel = None
        self._ambience_duck = 1.0  # reveal grammar: the corrupted reveal dips it
        self._heartbeat_active = False
        self._heartbeat_channel = None

        self._ready = False
        try:
            if not pygame.mixer.get_init():
                pygame.mixer.init(frequency=44100, channels=2)
            self._ready = pygame.mixer.get_init() is not None
        except pygame.error as exc:
            print(f"[audio] mixer init failed, running silent: {exc}", file=sys.stderr)
            self._ready = False

    # ------------------------------------------------------------------

    def _load(self, name: str):
        if name in self._sounds:
            return self._sounds[name]
        snd = None
        path = SFX_DIR / f"{name}.wav"
        if self._ready and path.exists():
            try:
                snd = pygame.mixer.Sound(str(path))
            except pygame.error as exc:
                if name not in self._missing_logged:
                    print(f"[audio] failed to load {name}.wav: {exc}", file=sys.stderr)
                    self._missing_logged.add(name)
        elif name not in self._missing_logged:
            print(f"[audio] missing sfx: {name}.wav (skipping)", file=sys.stderr)
            self._missing_logged.add(name)
        self._sounds[name] = snd
        return snd

    def play(self, name: str, vol: float = 1.0, pan: float = 0.5) -> None:
        if self.tap is not None:
            self.tap("sfx", name, vol, pan)
        if self.muted or not self._ready:
            return
        snd = self._load(name)
        if snd is None:
            return
        v = max(0.0, min(1.0, vol)) * self.sfx_vol * self.master_vol
        pan = max(0.0, min(1.0, pan))
        channel = snd.play()
        if channel is not None:
            channel.set_volume((1.0 - pan) * v, pan * v)

    # ------------------------------------------------------------------

    def handle_sounds(self, session, sounds, visible_instances=None) -> None:
        """Consume ("sound", name, room, x, y, vol) fx entries.

        `visible_instances` is the same list `Renderer.draw` consumes from
        `session.visible(...)`; pass it to get accurate stereo pan for
        sources currently on screen. Rooms not in that list (or when it is
        omitted) pan center -- correct for the horror-pacing case of
        hearing something before you can see it.
        """
        if not sounds:
            return
        proom = session.player_room()
        visible_rooms: dict[int, tuple] = {}
        if visible_instances:
            for room, xform, depth, clip_screen, walls, entry_edge, ents in visible_instances:
                visible_rooms.setdefault(room, xform)
        for ev in sounds:
            if ev[0] != "sound":
                continue
            _, name, room, x, y, vol = ev
            hops = session.sim.hop_distance(room, proom)
            if hops < 0:
                continue
            v = vol * (HOP_ATTENUATION ** hops)
            pan = 0.5
            xform = visible_rooms.get(room)
            if xform is not None:
                sx, _sy = necore.mat_apply(xform, x, y)
                w = max(1.0, float(session.screen_w))
                pan = max(0.0, min(1.0, sx / w))
            self.play(name, v, pan)

    # ------------------------------------------------------------------

    def ambience(self, name: str) -> None:
        if self._ambience_name == name:
            return
        self._ambience_name = name
        if self.tap is not None:
            self.tap("ambience", name, self.ambience_vol, 0.5)
        if self._ambience_channel is not None:
            self._ambience_channel.stop()
            self._ambience_channel = None
        if self.muted or not self._ready or not name:
            return
        snd = self._load(name)
        if snd is None:
            return
        channel = snd.play(loops=-1)
        if channel is not None:
            channel.set_volume(self.ambience_vol * self.master_vol
                               * self._ambience_duck)
            self._ambience_channel = channel

    def duck_ambience(self, frac: float) -> None:
        """Scale the running ambience loop (1.0 = normal). The corrupted
        expansion reveal dips the room while the bloom sours."""
        self._ambience_duck = max(0.0, min(1.0, frac))
        if self._ambience_channel is not None:
            self._ambience_channel.set_volume(
                self.ambience_vol * self.master_vol * self._ambience_duck)

    def update_heartbeat(self, session) -> None:
        want = session.hp < 30 and not session.dead
        if want == self._heartbeat_active:
            return
        self._heartbeat_active = want
        if self.tap is not None:
            self.tap("heartbeat_on" if want else "heartbeat_off",
                     "heartbeat", 0.5, 0.5)
        if want:
            if self.muted or not self._ready:
                return
            snd = self._load("heartbeat")
            if snd is None:
                return
            channel = snd.play(loops=-1)
            if channel is not None:
                channel.set_volume(0.5 * self.master_vol)
                self._heartbeat_channel = channel
        elif self._heartbeat_channel is not None:
            self._heartbeat_channel.stop()
            self._heartbeat_channel = None

    # ------------------------------------------------------------------

    def set_master(self, v: float) -> None:
        self.master_vol = max(0.0, min(1.0, v))

    def set_mute(self, muted: bool) -> None:
        self.muted = muted
        if muted and self._ready:
            pygame.mixer.stop()
