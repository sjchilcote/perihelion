"""What a type checker can prove about coordinate spaces, proved.

The runtime algebra raises `FrameMismatch` when two values from unrelated
spaces meet. That is the half that needs a running world, because a space
id is a runtime value. This file pins the OTHER half — the part mypy
settles before anything runs, from `game/stubs/necore.pyi`:

    place - place   -> difference
    place + diff    -> place
    place + place   -> REJECTED, there is no such overload
    diff  + diff    -> difference
    a raw tuple where a place belongs -> REJECTED
    two bare floats where an Offset belongs -> REJECTED

WHY BOTH HALVES OF THE TEST. A stub that rejected everything would pass a
test that only checked the refusals, and would be useless. So the legal
forms are checked to be ACCEPTED in the same pass, on the same fixture —
conservation of expected evidence: if every form were rejected, the
rejections would carry no information.

Deliberately NOT asserted: that `mypy` over the whole of `game/perihelion`
is clean. It is not — there are a few hundred pre-existing findings in
untyped code (`app.py` attribute access on `object`, and so on) that have
nothing to do with coordinates and would be a separate job to clear. The
config in pyproject.toml runs the tree-wide check for anyone who wants it;
this test is the part that gates.
"""
from __future__ import annotations

import re
import shutil
import subprocess
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[2]

# Each entry: (source line, must mypy reject it?)
#
# The reason column is the point of the whole system, so it is written out
# rather than implied by a line number.
CASES: list[tuple[str, bool, str]] = [
    ("d1 = here - there", False,
     "a difference between two places is the torsor's own operation"),
    ("p1 = here + d1", False,
     "a place plus a difference is a place"),
    ("d2 = d1 + d1", False,
     "differences add"),
    ("d3 = d1 * 2.0", False,
     "a difference scales"),
    ("n1 = d1.length", False,
     "a length is a scalar"),
    ("t1 = here.toward(there)", False,
     "the named form of the subtraction"),
    ("f1 = here.distance_to(there)", False,

     "distance is a scalar, measured in the left operand's space"),
    ("bad1 = here + there", True,
     "PLACE + PLACE. There is no origin to add two places about, and the "
     "absence of this overload IS the torsor structure"),
    ("bad2 = here - d1", True,
     "a place minus a difference is spelled `here + (-d1)`; the reversed "
     "form is the sign error that reads correctly"),
    ("bad3 = sim.set_vel(1, 4.0)", True,
     "two bare floats where an Offset belongs — the shape of the old API, "
     "and the shape of the defect"),
    ("bad4 = sim.spawn(3, 1.0, 2.0, 5.0, 1.0, 0)", True,
     "a polygon index paired with loose numbers: the pairing that could "
     "drift"),
    ("bad5 = sim.develop((1.0, 2.0), here.space)", True,
     "a raw tuple where a place belongs"),
    ("bad6 = here.toward(d1)", True,
     "a difference where a place belongs — the two are not interchangeable "
     "and that is the whole point of splitting them"),
]

FIXTURE = """# generated by test_mypy_frame_types.py
import necore


def scene(sim: necore.Sim, here: necore.Coordinate,
          there: necore.Coordinate) -> None:
"""


@pytest.mark.slow
def test_mypy_settles_the_place_versus_difference_split():
    if shutil.which("mypy") is None:
        try:
            import mypy  # noqa: F401
        except ImportError:
            pytest.skip("mypy is not installed in this environment")

    tmp = ROOT / "out" / "mypy_frame_fixture"
    tmp.mkdir(parents=True, exist_ok=True)
    src = tmp / "frame_cases.py"
    lines = [FIXTURE]
    for i, (code, _reject, _why) in enumerate(CASES):
        lines.append(f"    {code}  # case {i}\n")
    src.write_text("".join(lines))

    proc = subprocess.run(
        [sys.executable, "-m", "mypy",
         "--no-incremental", "--no-error-summary",
         "--follow-imports", "silent",
         "--python-version", "3.11",
         "--check-untyped-defs",
         "--ignore-missing-imports",
         "--no-site-packages",
         str(src)],
        cwd=str(ROOT), capture_output=True, text=True, timeout=600,
        env={**__import__("os").environ,
             "MYPYPATH": str(ROOT / "game" / "stubs")},
    )
    flagged: set[int] = set()
    for m in re.finditer(r"frame_cases\.py:(\d+):", proc.stdout):
        # line 1 is the comment, 2 the import, 5-6 the signature: the
        # cases start after the FIXTURE preamble
        flagged.add(int(m.group(1)) - (FIXTURE.count("\n") + 1))

    problems = []
    for i, (code, reject, why) in enumerate(CASES):
        hit = i in flagged
        if reject and not hit:
            problems.append(f"ACCEPTED but must be rejected: {code!r} — {why}")
        elif not reject and hit:
            problems.append(f"REJECTED but must be accepted: {code!r} — {why}")
    assert not problems, (
        "the type-level half of the coordinate system is not what it "
        "claims:\n  " + "\n  ".join(problems)
        + f"\n\nmypy said:\n{proc.stdout}")
