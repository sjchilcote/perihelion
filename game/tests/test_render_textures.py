"""Bespoke per-polygon floor textures (ARTSTYLE_DIRECTION.md lever one):
OP_TEX_FILL (rust) and its numpy mirror (pygame) must draw the same
texture pixel-identically, and the lightmap multiply (zero ambient, per
the director's order) must still apply to textured pixels exactly as it
does to flat fills.

The texture used here is synthetic (solid white, generated by the test
itself) rather than committed art, per the task: a flat-white texture
sampled with no light reaching it renders pure (0,0,0); sampled under a
light, brightness must fall off with distance from the light. Either
proof is formula-agnostic -- it does not hard-code the lightmap's own
constants into the test.
"""

