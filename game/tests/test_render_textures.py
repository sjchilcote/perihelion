"""Bespoke per-room floor textures (ARTSTYLE_DIRECTION.md lever one):
OP_TEX_FILL (rust) and its numpy mirror (pygame) must draw the same
texture pixel-identically, and the darkness field must still apply to
textured pixels exactly as it does to flat fills.

The texture used here is synthetic (solid white, generated by the test
itself) rather than committed art, per the task: a flat-white texture
sampled without darkness would render pure (255,255,255) everywhere it
covers; any deviation from that can only come from the darkness multiply,
which gives a formula-agnostic behavioral proof that darkness reached the
textured pixels without hard-coding the LUT's constants into the test.
"""

from __future__ import annotations

import os

os.environ.setdefault("SDL_VIDEODRIVER", "dummy")
os.environ.setdefault("SDL_AUDIODRIVER", "dummy")

import numpy as np
import pygame
import pytest

import necore

from perihelion.app import build_debug_level
from perihelion.render import INTERNAL_H, INTERNAL_W, Renderer, TEXTURE_DIR
from perihelion.sim import GameSession, InputFrame
from perihelion import texture_geom

pytestmark = pytest.mark.skipif(
    not hasattr(necore, "Raster"),
    reason="this necore build has no Raster (rust render backend)",
)


def _write_white_texture(root, level_id: str, room_index: int, w: int, h: int) -> None:
    (root / level_id).mkdir(parents=True, exist_ok=True)
    surf = pygame.Surface((w, h))
    surf.fill((255, 255, 255))
    pygame.image.save(surf, str(root / level_id / f"room_{room_index}.png"))


def _make_textured_session(monkeypatch, textures_root, seed=1234):
    """Debug level, room 0 given a synthetic all-white texture at the
    convention path; level_id set as if it had been loaded from disk."""
    level = build_debug_level()
    level.level_id = "texparity"
    w, h = texture_geom.texture_size_for_room(level.room_verts[0])
    _write_white_texture(textures_root, level.level_id, 0, w, h)
    monkeypatch.setattr("perihelion.render.TEXTURE_DIR", textures_root)
    session = GameSession(level, seed=seed, screen=(INTERNAL_W, INTERNAL_H))
    return session


def _draw(session, backend, ticks=20):
    ren = Renderer(session, backend=backend)
    surf = pygame.Surface((INTERNAL_W, INTERNAL_H))
    for tick in range(1, ticks + 1):
        session.tick(InputFrame(mx=0.0, my=0.0, ax=INTERNAL_W / 2, ay=INTERNAL_H / 2,
                                fire=False, alt=False, interact=False, weapon=0))
        ren.consume_fx(session.fx)
    ren.draw(surf)
    return surf


@pytest.fixture(scope="module")
def pygame_ready():
    pygame.init()
    yield
    pygame.quit()


def test_texture_size_helper_matches_room_bbox():
    level = build_debug_level()
    verts = level.room_verts[0]  # rect(0, 0, 160, 120) -> local bbox 160x120
    w, h = texture_geom.texture_size_for_room(verts)
    assert (w, h) == (480, 360)  # 160*3, 120*3


def test_textured_floor_matches_across_backends(pygame_ready, tmp_path, monkeypatch):
    session_rust = _make_textured_session(monkeypatch, tmp_path / "rust")
    surf_rust = _draw(session_rust, "rust")

    session_pg = _make_textured_session(monkeypatch, tmp_path / "pg", seed=1234)
    surf_pg = _draw(session_pg, "pygame")

    assert pygame.image.tobytes(surf_rust, "RGB") == pygame.image.tobytes(surf_pg, "RGB")


def test_textured_floor_differs_from_untextured_fallback(pygame_ready, tmp_path, monkeypatch):
    textured = _draw(_make_textured_session(monkeypatch, tmp_path / "tex"), "rust")

    # same level, but no texture file anywhere -> falls back to the flat
    # OP_CLIP_FILL floor color exactly as today
    level = build_debug_level()
    level.level_id = "notex"
    monkeypatch.setattr("perihelion.render.TEXTURE_DIR", tmp_path / "empty")
    session_flat = GameSession(level, seed=1234, screen=(INTERNAL_W, INTERNAL_H))
    flat = _draw(session_flat, "rust")

    assert pygame.image.tobytes(textured, "RGB") != pygame.image.tobytes(flat, "RGB")


def test_darkness_applies_to_textured_pixels(pygame_ready, tmp_path, monkeypatch):
    """A solid-white texture, undarkened, renders (255,255,255) everywhere
    it covers. If darkness still applies to OP_TEX_FILL pixels, brightness
    must fall off monotonically-ish with distance from screen center (the
    darkness field's own center) -- i.e. a near-center covered pixel must
    be strictly brighter than a far-from-center covered pixel."""
    surf = _draw(_make_textured_session(monkeypatch, tmp_path / "dk"), "rust")
    arr = pygame.surfarray.pixels3d(surf)  # (W, H, 3)
    cx, cy = INTERNAL_W / 2.0, INTERNAL_H / 2.0

    # "texture-covered" pixels: our white texture is the only thing in this
    # scene bright enough that every channel exceeds 220 (walls/props/
    # entities in build_debug_level() all fall well short of that on at
    # least one channel).
    bright = np.all(arr > 220, axis=2)  # (W, H) bool, matches arr's (x, y) axes
    xs, ys = np.nonzero(bright)
    assert len(xs) > 20, "expected a sizeable patch of the synthetic white texture"

    dist2 = (xs - cx) ** 2 + (ys - cy) ** 2
    near_i = np.argmin(dist2)
    far_i = np.argmax(dist2)
    near_px = arr[xs[near_i], ys[near_i]].astype(int)
    far_px = arr[xs[far_i], ys[far_i]].astype(int)
    del arr

    assert far_px.sum() < near_px.sum(), (
        f"expected darkness falloff on textured pixels: near-center {near_px} "
        f"should be brighter than far-from-center {far_px}"
    )
    # the near-center pixel is close to raw (255,255,255); the far pixel
    # must actually have been dimmed, not just naturally darker geometry
    assert far_px.sum() < 3 * 255
