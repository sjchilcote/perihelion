_NEAR_LIGHT = LightSpec(polygon=0, pos=(-40.0, 0.0), color=(255, 255, 255),
                         intensity=3.0, radius=250.0, kind="static")


def _dark_and_lit_sessions(monkeypatch, tmp_path, textured):
    """Two otherwise-identical sessions (same seed, same level, same
    camera path): one with NO light at all (player lamp doused, no world
    lights) and one with ONLY `_NEAR_LIGHT` added (player lamp still
    doused). Same polygon-0 geometry either way, so screen coordinates line
    up exactly between the pair."""
    if textured:
        dark = _make_textured_session(monkeypatch, tmp_path / "dk",
                                       douse_lamp=True)
        lit = _make_textured_session(monkeypatch, tmp_path / "lit",
                                      light=_NEAR_LIGHT, douse_lamp=True)
    else:
        monkeypatch.setattr("perihelion.render.TEXTURE_DIR", tmp_path / "empty")
        level_dark = build_debug_level()
        level_dark.level_id = "notex-dark"
        dark = GameSession(level_dark, seed=1234, screen=(INTERNAL_W, INTERNAL_H))
        dark.douse_player_lights()
        level_lit = build_debug_level()
        level_lit.level_id = "notex-lit"
        level_lit.lights.append(_NEAR_LIGHT)
        lit = GameSession(level_lit, seed=1234, screen=(INTERNAL_W, INTERNAL_H))
        lit.douse_player_lights()
    return dark, lit


@pytest.mark.parametrize("backend", ["rust"])
@pytest.mark.parametrize("textured", [True, False])
def test_zero_ambient_black_then_light_falloff_on_world_pixels(
        pygame_ready, tmp_path, monkeypatch, backend, textured):
    """The director's order, literal: "unless there's a specific light
    source, the worklight is the only light" -- a world-layer pixel in a
    polygon no ENABLED light reaches renders BLACK, textured or flat, both
    backends; adding a real static light must then light that same pixel
    up (falloff still works, driven by a real light instead of a screen-
    space vignette).

    The sample point is DISCOVERED, not hardcoded: it's wherever the
    lit/unlit pair actually differ (away from the frame edge, to dodge
    HUD/crosshair chrome that's on the always-visible overlay layer and
    legitimately identical either way) -- this avoids pinning a magic
    coordinate that might land on HUD instead of floor.

    Fail-first verified: restored the screen-space vignette multiply (the
    old `_apply_darkness`/raster.rs `dark` LUT ambient field) in place of
    the zero-ambient lightmap -- the "dark" render was no longer black at
    the discovered sample point (near-white/mid-grey instead) for every
    (backend, textured) combination. Reverted before committing."""
    dark_session, lit_session = _dark_and_lit_sessions(monkeypatch, tmp_path, textured)
    dark = _draw(dark_session, backend)
    lit = _draw(lit_session, backend)

    diff = np.abs(dark.astype(int) - lit.astype(int)).sum(axis=2)
    margin = 40
    diff[:margin, :] = diff[-margin:, :] = 0
    diff[:, :margin] = diff[:, -margin:] = 0
    x, y = np.unravel_index(np.argmax(diff), diff.shape)
    assert diff[x, y] > 30, "lit and unlit renders never diverge anywhere interior"

    assert tuple(int(c) for c in dark[x, y]) == (0, 0, 0), (
        f"{'textured' if textured else 'flat'}/{backend}: unlit pixel at "
        f"({x},{y}) should be black, got {tuple(dark[x, y])}")
    assert int(lit[x, y].sum()) > 30, (
        f"{'textured' if textured else 'flat'}/{backend}: lit pixel at "
        f"({x},{y}) should show the static light, got {tuple(lit[x, y])}")
