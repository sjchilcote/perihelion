def _write_white_texture(root, level_id: str, polygon_index: int, w: int, h: int) -> None:
    (root / level_id).mkdir(parents=True, exist_ok=True)
    surf = pygame.Surface((w, h))
    surf.fill((255, 255, 255))
    pygame.image.save(surf, str(root / level_id / f"polygon_{polygon_index}.png"))


def _make_textured_session(monkeypatch, textures_root, seed=1234, light=None,
                            douse_lamp=False):
    """Debug level, polygon 0 given a synthetic all-white texture at the
    convention path; level_id set as if it had been loaded from disk.

    `light`, if given, is appended to the level's `lights` list. `douse_
    lamp` zeroes the player's own attached work lamp so it is not a second,
    untracked illuminant in tests that want ONLY `light` (or no light at
    all) contributing -- same isolation `test_root_invariance._douse_
    player_lamp` uses. Left ON by default: with zero ambient, the parity/
    fallback tests below need SOME light in the scene, and the player's
    own attached lamp is the honest default source (the frame's work
    lamp is the only light that always exists)."""
    level = build_debug_level()
    level.level_id = "texparity"
    w, h = texture_geom.texture_size_for_polygon(level.polygon_verts[0])
    _write_white_texture(textures_root, level.level_id, 0, w, h)
    monkeypatch.setattr("perihelion.render.TEXTURE_DIR", textures_root)
    if light is not None:
        level.lights.append(light)
    session = GameSession(level, seed=seed, screen=(INTERNAL_W, INTERNAL_H))
    if douse_lamp:
        session.douse_player_lights()
    return session


def _draw(session, backend, ticks=20):
    ren = Renderer(session)
    surf = pygame.Surface((INTERNAL_W, INTERNAL_H))
    for tick in range(1, ticks + 1):
        session.tick(InputFrame(mx=0.0, my=0.0, ax=INTERNAL_W / 2, ay=INTERNAL_H / 2,
                                fire=False, alt=False, interact=False, weapon=0))
        ren.consume_fx(session.fx)
    return ren.draw(surf)


