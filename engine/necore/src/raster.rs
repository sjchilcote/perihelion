/// Python `int(round(x))`: round half to even, like the renderer's `_pt`.
#[inline]
fn py_round(x: f64) -> i32 {
    x.round_ties_even() as i32
}

/// C `(int)` cast of a double: truncation toward zero (`pg_IntFromObj`,
/// `pygame.Rect` float handling).
#[inline]
fn c_int(x: f64) -> i32 {
    x as i32
}

/// Winding-independent ray-cast point-in-polygon, ported verbatim from
/// render.py `_point_in_poly` (including the strict `x < x_at` comparison).
/// Clip polygons can be CW under chirality-flipped portals, so this must not
/// assume a winding order.
fn point_in_poly(x: f64, y: f64, poly: &[Vec2]) -> bool {
    let n = poly.len();
    if n < 3 {
        return false;
    }
    let mut inside = false;
    let mut j = n - 1;
    for i in 0..n {
        let (xi, yi) = (poly[i].x, poly[i].y);
        let (xj, yj) = (poly[j].x, poly[j].y);
        if (yi > y) != (yj > y) {
            let x_at = (xj - xi) * (y - yi) / (yj - yi) + xi;
            if x < x_at {
                inside = !inside;
            }
        }
        j = i;
    }
    inside
}

/// SDL_Rect-alike; empty when w <= 0 or h <= 0.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
struct IRect {
    x: i32,
    y: i32,
    w: i32,
    h: i32,
}

impl IRect {
    fn intersect(self, o: IRect) -> IRect {
        let x1 = self.x.max(o.x);
        let y1 = self.y.max(o.y);
        let x2 = (self.x + self.w).min(o.x + o.w);
        let y2 = (self.y + self.h).min(o.y + o.h);
        IRect {
            x: x1,
            y: y1,
            w: x2 - x1,
            h: y2 - y1,
        }
    }

    fn is_empty(self) -> bool {
        self.w <= 0 || self.h <= 0
    }
}

// ---------------------------------------------------------------------------
// canvas: a pixel plane + clip rect + write mode (the SDL_Surface stand-in)
// ---------------------------------------------------------------------------

#[derive(Clone, Copy)]
enum PxWrite {
    /// Opaque RGBA store.
    Set([u8; 4]),
    /// Saturating additive RGB (BLEND_RGB_ADD parity); alpha untouched.
    Add([u8; 3]),
    /// Single-byte store (coverage plane).
    Mask(u8),
}

struct Canvas<'a> {
    buf: &'a mut [u8],
    /// Bytes per pixel: 4 for RGBA planes, 1 for the coverage mask.
    bpp: usize,
    /// Surface width in pixels (row stride = w * bpp).
    w: i32,
    /// Active clip rect (already intersected with the surface bounds).
    clip: IRect,
    px: PxWrite,
}

impl Canvas<'_> {
    #[inline]
    fn write(&mut self, x: i32, y: i32) {
        let off = (y as usize * self.w as usize + x as usize) * self.bpp;
        match self.px {
            PxWrite::Set(c) => self.buf[off..off + 4].copy_from_slice(&c),
            PxWrite::Add(c) => {
                for (i, &s) in c.iter().enumerate() {
                    let d = self.buf[off + i] as u16 + s as u16;
                    self.buf[off + i] = if d <= 255 { d as u8 } else { 255 };
                }
            }
            PxWrite::Mask(m) => self.buf[off] = m,
        }
    }

    /// pygame `set_at`: bounds/clip check per pixel, then write.
    #[inline]
    fn set_at(&mut self, x: i32, y: i32) {
        if x < self.clip.x
            || x >= self.clip.x + self.clip.w
            || y < self.clip.y
            || y >= self.clip.y + self.clip.h
        {
            return;
        }
        self.write(x, y);
    }

    /// pygame `drawhorzline`: raw inclusive span, caller has clipped and
    /// ordered. Spans are the fill hot path (coverage masks + floor fills
    /// paint ~1M px/frame at 400 instances), so Set/Mask bypass the
    /// per-pixel dispatch of `write` — byte-identical output, just batched.
    fn hline_raw(&mut self, x1: i32, y: i32, x2: i32) {
        debug_assert!(x1 <= x2);
        let row = y as usize * self.w as usize;
        match self.px {
            PxWrite::Set(c) => {
                debug_assert_eq!(self.bpp, 4);
                let span = &mut self.buf[(row + x1 as usize) * 4..(row + x2 as usize + 1) * 4];
                for px in span.chunks_exact_mut(4) {
                    px.copy_from_slice(&c);
                }
            }
            PxWrite::Mask(m) => {
                debug_assert_eq!(self.bpp, 1);
                self.buf[row + x1 as usize..row + x2 as usize + 1].fill(m);
            }
            PxWrite::Add(_) => {
                for x in x1..=x2 {
                    self.write(x, y);
                }
            }
        }
    }

    /// pygame `drawhorzlineclip(bounding)`: order, clamp to clip, draw.
    fn hline_clip(&mut self, x1: i32, y: i32, x2: i32) {
        if y < self.clip.y || y >= self.clip.y + self.clip.h {
            return;
        }
        let (mut a, mut b) = (x1, x2);
        if b < a {
            std::mem::swap(&mut a, &mut b);
        }
        a = a.max(self.clip.x);
        b = b.min(self.clip.x + self.clip.w - 1);
        if b < self.clip.x || a >= self.clip.x + self.clip.w {
            return;
        }
        self.hline_raw(a, y, b);
    }
}

