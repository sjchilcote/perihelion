    /// OP_CLIP_FILL paints exactly the pixels OP_POLY_FILL paints for the
    /// same (fractional, f64) polygon — and therefore exactly the coverage
    /// pixels add_clip painted, since coverage uses the same fill: the
    /// floor/no-seams-mask identity the renderer's rust backend relies on.
    #[test]
    fn clip_fill_matches_poly_fill_and_coverage() {
        let poly = [3.4, 1.6, 17.5, 2.5, 14.2, 12.8, 2.1, 9.9];

        let mut a = Raster::new(20, 16);
        a.set_darkness(false);
        a.begin(0x0000_00FF);
        let ci = a.add_clip(&poly, true).unwrap();
        let (c, f) = cmd(
            OP_CLIP_FILL,
            pack_flags(LAYER_WORLD, CLIPMODE_NONE, false, false, 0),
            ci,
            IDX_NONE,
            WHITE,
            &[],
        );
        a.draw(&c, &f).unwrap();
        let cov = a.coverage.clone();
        let fa = a.finish();

        let fb = {
            let mut b = Raster::new(20, 16);
            b.set_darkness(false);
            b.begin(0x0000_00FF);
            let (c, f) = cmd(
                OP_POLY_FILL,
                pack_flags(LAYER_WORLD, CLIPMODE_NONE, false, false, 0),
                IDX_NONE,
                IDX_NONE,
                WHITE,
                &poly,
            );
            b.draw(&c, &f).unwrap();
            b.finish()
        };
        assert_eq!(fa, fb, "clip fill != poly fill of the same polygon");
        for (i, px) in fa.chunks_exact(4).enumerate() {
            let lit = px[0] != 0;
            assert_eq!(
                lit,
                cov[i] == 255,
                "floor/coverage mismatch at pixel {i}"
            );
        }
    }

    #[test]
    fn tex_fill_samples_nearest_and_matches_coverage() {
        // Identity xform: screen == room-local. bbox_min = (0,0), so texel
        // = floor((px+0.5)*TEX_DENSITY), clamped. 4x4 raster, 12x12 texture
        // (4 * TEX_DENSITY(3) = 12), value at texel (tx,ty) = (tx*20, ty*20, 128).
        let mut r = Raster::new(4, 4);
        r.set_darkness(false);
        let mut tex = vec![0u8; 12 * 12 * 3];
        for ty in 0..12usize {
            for tx in 0..12usize {
                let off = (ty * 12 + tx) * 3;
                tex[off] = (tx * 20) as u8;
                tex[off + 1] = (ty * 20) as u8;
                tex[off + 2] = 128;
            }
        }
        r.set_texture(7, 12, 12, &tex).unwrap();
        r.begin(0x0000_00FF);
        let ci = r.add_clip(&[0.0, 0.0, 4.0, 0.0, 4.0, 4.0, 0.0, 4.0], true).unwrap();
        let xi = r.add_xform(Mat3::IDENTITY.m);
        let fl = pack_flags(LAYER_WORLD, CLIPMODE_NONE, false, false, 0);
        let (c, f) = cmd(OP_TEX_FILL, fl, ci, xi, 7, &[0.0, 0.0]);
        r.draw(&c, &f).unwrap();
        let cov = r.coverage.clone();
        let frame = r.finish();
        for py in 0..4usize {
            for px in 0..4usize {
                let i = py * 4 + px;
                let off = i * 4;
                let lit = frame[off] != 0 || frame[off + 1] != 0 || frame[off + 2] != 0;
                assert_eq!(lit, cov[i] == 255, "floor/coverage mismatch at ({px},{py})");
                if cov[i] == 255 {
                    let tx = (((px as f64 + 0.5) * TEX_DENSITY).floor() as usize).min(11);
                    let ty = (((py as f64 + 0.5) * TEX_DENSITY).floor() as usize).min(11);
                    assert_eq!(frame[off], (tx * 20) as u8, "R at ({px},{py})");
                    assert_eq!(frame[off + 1], (ty * 20) as u8, "G at ({px},{py})");
                    assert_eq!(frame[off + 2], 128, "B at ({px},{py})");
                }
            }
        }
    }

