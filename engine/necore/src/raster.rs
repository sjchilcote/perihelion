    #[test]
    fn finish_is_idempotent_and_draws_after_finish_fail() {
        let mut r = Raster::new(8, 8);
        r.begin(0x0000_00FF);
        let f = pack_flags(LAYER_WORLD, CLIPMODE_NONE, false, false, 0);
        let quad = [1.0, 1.0, 6.0, 1.0, 6.0, 6.0, 1.0, 6.0];
        draw_one(&mut r, OP_POLY_FILL, f, IDX_NONE, IDX_NONE, WHITE, &quad);
        // Darkness is on: a second compose would double-darken if it ran.
        let a = r.finish();
        let b = r.finish();
        assert_eq!(a, b, "finish must be idempotent within a frame");
        // Post-finish mutation is an emitter bug and fails loudly.
        let (c, fl) = cmd(
            OP_CIRCLE_FILL,
            0,
            IDX_NONE,
            IDX_NONE,
            WHITE,
            &[4.0, 4.0, 2.0],
        );
        assert!(r.draw(&c, &fl).is_err());
        assert!(r.add_clip(&[0.0, 0.0, 4.0, 0.0, 4.0, 4.0], true).is_err());
        // begin() re-arms the frame.
        r.begin(0x0000_00FF);
        r.draw(&c, &fl).unwrap();
    }

