pub struct Raster {
    w: i32,
    h: i32,
    /// RGBA8 world plane; also the compositing target.
    world: Vec<u8>,
    /// RGBA8 entity plane (binary alpha).
    entity: Vec<u8>,
    /// u8 coverage plane: union of the instance clip polygons.
    coverage: Vec<u8>,
    /// Per-frame lightmap, 3 bytes per pixel (R, G, B multipliers),
    /// uploaded by `set_lightmap`; reset to all-zero (black -- zero
    /// ambient) at the top of every `begin()`. This is the world's SOLE
    /// illumination when `darkness_on`, not a screen-space vignette.
    lightmap: Vec<u8>,
    darkness_on: bool,
    /// Set by the first compose since `begin`. Compositing is destructive
    /// (entity fold + darkness multiply mutate the world plane), so it runs
    /// once per frame; later `finish*` calls return the same frame and
    /// later draws are rejected until the next `begin`.
    composed: bool,
    clips: Vec<ClipEntry>,
    xforms: Vec<XformEntry>,
    overlay: Vec<OverlayJob>,
    /// Registered room textures (`set_texture`), keyed by caller-chosen id.
    /// Persists across `begin()` — uploaded once, reused every frame.
    textures: std::collections::HashMap<u32, Texture>,
}

impl Raster {
    /// Fixed-size rasterizer. `lightmap` starts all-zero (black): with no
    /// `set_lightmap` upload, a `darkness_on` frame renders the world plane
    /// pure black, which is correct -- zero ambient, no light reached it.
    pub fn new(w: usize, h: usize) -> Raster {
        assert!(w > 0 && h > 0, "raster dimensions must be positive");
        let npx = w * h;
        Raster {
            w: w as i32,
            h: h as i32,
            world: vec![0; npx * 4],
            entity: vec![0; npx * 4],
            coverage: vec![0; npx],
            lightmap: vec![0; npx * 3],
            darkness_on: true,
            composed: false,
            clips: Vec::new(),
            xforms: Vec::new(),
            overlay: Vec::new(),
            textures: std::collections::HashMap::new(),
        }
    }

    /// Upload (or replace) a texture: RGB8, row-major, `data.len() ==
    /// w*h*3`. Persists across frames — call once per texture, not per
    /// frame. `id` is caller-chosen (the game uses the engine room index).
    pub fn set_texture(&mut self, id: u32, w: usize, h: usize, data: &[u8]) -> Result<(), RasterError> {
        if w == 0 || h == 0 {
            return err("set_texture: width and height must be positive");
        }
        let want = w * h * 3;
        if data.len() != want {
            return err(format!(
                "set_texture: data is {} bytes, need {want} (w*h*3, RGB8)",
                data.len()
            ));
        }
        self.textures.insert(id, Texture { w, h, rgb: data.to_vec() });
        Ok(())
    }

    pub fn width(&self) -> usize {
        self.w as usize
    }

    pub fn height(&self) -> usize {
        self.h as usize
    }

    /// Start a frame: clear all planes and per-frame tables.
    pub fn begin(&mut self, bg_rgba: u32) {
        let bg = unpack_rgba(bg_rgba);
        for px in self.world.chunks_exact_mut(4) {
            px.copy_from_slice(&bg);
        }
        self.entity.fill(0);
        self.coverage.fill(0);
        self.lightmap.fill(0);  // zero ambient by default every frame
        self.clips.clear();
        self.xforms.clear();
        self.overlay.clear();
        self.composed = false;
    }

    pub fn set_darkness(&mut self, on: bool) {
        self.darkness_on = on;
    }

    /// Upload this frame's lightmap: RGB8, row-major, `rgb.len() ==
    /// w*h*3` -- one multiplier triple per pixel, the world's SOLE
    /// illumination when `darkness_on` (see module docs). Call once per
    /// frame, before `finish`/`finish_into`; a frame with no call keeps
    /// the all-zero (black) map `begin()` reset it to.
    pub fn set_lightmap(&mut self, rgb: &[u8]) -> Result<(), RasterError> {
        let want = self.lightmap.len();
        if rgb.len() != want {
            return err(format!(
                "set_lightmap: data is {} bytes, need {want} (w*h*3, RGB8)",
                rgb.len()
            ));
        }
        self.lightmap.copy_from_slice(rgb);
        Ok(())
    }

    /// Register an instance's convex screen-space clip polygon (flat
    /// [x0,y0,x1,y1,...]). With `coverage`, also scan-fill it into the
    /// coverage mask — the union that implements the no-seams invariant,
    /// using the same fill (and the same rounding) as POLY_FILL so mask and
    /// floor coincide pixel-exactly.
    pub fn add_clip(&mut self, pts: &[f64], coverage: bool) -> Result<u32, RasterError> {
        if self.composed {
            return err("add_clip after finish; call begin to start a new frame");
        }
        if pts.len() % 2 != 0 {
            return err("add_clip: flat point list must have even length");
        }
        if pts.len() < 6 {
            return err("add_clip: clip polygon needs at least 3 points");
        }
        let poly: Vec<Vec2> = pts.chunks_exact(2).map(|p| v(p[0], p[1])).collect();

        let (mut min_x, mut min_y) = (f64::INFINITY, f64::INFINITY);
        let (mut max_x, mut max_y) = (f64::NEG_INFINITY, f64::NEG_INFINITY);
        for p in &poly {
            min_x = min_x.min(p.x);
            min_y = min_y.min(p.y);
            max_x = max_x.max(p.x);
            max_y = max_y.max(p.y);
        }
        if !(min_x.is_finite() && min_y.is_finite() && max_x.is_finite() && max_y.is_finite()) {
            return err("add_clip: non-finite clip polygon");
        }
        // pygame.Rect parity: int() truncation, extent int(max-min)+1.
        let bbox = IRect {
            x: c_int(min_x),
            y: c_int(min_y),
            w: c_int(max_x - min_x) + 1,
            h: c_int(max_y - min_y) + 1,
        };

        if coverage {
            let (xs, ys) = round_pts(&poly);
            let mut c = Canvas {
                buf: &mut self.coverage,
                bpp: 1,
                w: self.w,
                clip: IRect {
                    x: 0,
                    y: 0,
                    w: self.w,
                    h: self.h,
                },
                px: PxWrite::Mask(255),
            };
            pg_poly_fill(&mut c, &xs, &ys);
        }

        let hps = geom::polygon_halfplanes(&poly);
        self.clips.push(ClipEntry {
            pts: poly,
            hps,
            bbox,
        });
        Ok((self.clips.len() - 1) as u32)
    }

    /// Register a row-major Mat3 (the instance xform from `visible()`).
    pub fn add_xform(&mut self, m9: [f64; 9]) -> u32 {
        let m = Mat3 { m: m9 };
        let d = m.apply_dir(v(1.0, 0.0));
        self.xforms.push(XformEntry {
            m,
            scale: d.x.hypot(d.y),
        });
        (self.xforms.len() - 1) as u32
    }

    /// Execute a command stream (see module docs for the wire format).
    pub fn draw(&mut self, cmds: &[u32], coords: &[f32]) -> Result<(), RasterError> {
        self.exec_stream(cmds, coords, None)
    }

    /// Static-blob replay: same wire format, but every command's CLIP and
    /// XFORM header fields are overridden by the arguments (the per-room
    /// detail cache path).
    pub fn draw_with_overrides(
        &mut self,
        cmds: &[u32],
        coords: &[f32],
        xform_idx: u32,
        clip_idx: u32,
    ) -> Result<(), RasterError> {
        self.exec_stream(cmds, coords, Some((xform_idx, clip_idx)))
    }

    fn exec_stream(
        &mut self,
        cmds: &[u32],
        coords: &[f32],
        overrides: Option<(u32, u32)>,
    ) -> Result<(), RasterError> {
        if self.composed {
            return err("draw after finish; call begin to start a new frame");
        }
        if cmds.len() % HDR_WORDS != 0 {
            return err(format!(
                "command stream length {} is not a multiple of {HDR_WORDS}",
                cmds.len()
            ));
        }
        let mut fi = 0usize;
        for hdr in cmds.chunks_exact(HDR_WORDS) {
            let (op, flags, rgba, n) = (hdr[0], hdr[1], hdr[4], hdr[5] as usize);
            let (clip_idx, xform_idx) = match overrides {
                Some((xi, ci)) => (ci, xi),
                None => (hdr[2], hdr[3]),
            };
            let nfloats = match op {
                OP_POLY_FILL | OP_POLY_OUTLINE | OP_POLYLINE => 2 * n,
                OP_CIRCLE_FILL | OP_CIRCLE_OUTLINE | OP_GLOW => 3,
                OP_RECT_FILL | OP_RECT_OUTLINE => 4,
                OP_CLIP_FILL => 0,
                OP_TEX_FILL => 2,
                _ => return err(format!("unknown opcode {op}")),
            };
            if coords.len() - fi < nfloats {
                return err(format!(
                    "coord stream exhausted: op {op} needs {nfloats} floats, {} left",
                    coords.len() - fi
                ));
            }
            let payload = &coords[fi..fi + nfloats];
            fi += nfloats;
            self.exec_cmd(op, flags, clip_idx, xform_idx, rgba, n, payload)?;
        }
        if fi != coords.len() {
            return err(format!(
                "coord stream has {} unconsumed floats",
                coords.len() - fi
            ));
        }
        Ok(())
    }

    #[allow(clippy::too_many_arguments)]
    fn exec_cmd(
        &mut self,
        op: u32,
        flags: u32,
        clip_idx: u32,
        xform_idx: u32,
        rgba_u32: u32,
        n: usize,
        payload: &[f32],
    ) -> Result<(), RasterError> {
        let layer = flags & 3;
        let clipmode = (flags >> 2) & 3;
        let closed = flags & FLAG_CLOSED != 0;
        let radius_scaled = flags & FLAG_RADIUS_SCALED != 0;
        let width = ((flags >> 8) & 0xFF) as i32;
        let rgba = unpack_rgba(rgba_u32);

        if layer > LAYER_OVERLAY {
            return err(format!("bad layer {layer} in flags {flags:#x}"));
        }
        if op != OP_GLOW && op != OP_TEX_FILL && rgba[3] != 0xFF {
            // Phase 1 draws opaque only; a stray alpha means a broken
            // emitter (and would silently defeat the binary-alpha fold).
            // OP_TEX_FILL repurposes the RGBA word as a texture id, not a
            // color, so it is exempt from this check (like OP_GLOW).
            return err(format!(
                "op {op}: alpha must be 0xFF in phase 1, got {:#x}",
                rgba[3]
            ));
        }
        if op == OP_TEX_FILL && layer != LAYER_WORLD {
            return err("tex fill must be on the world layer");
        }

        let xform = if xform_idx == IDX_NONE {
            None
        } else {
            Some(
                self.xforms
                    .get(xform_idx as usize)
                    .ok_or_else(|| RasterError(format!("bad xform index {xform_idx}")))?,
            )
        };
        let clip = if clip_idx == IDX_NONE {
            None
        } else {
            Some(
                self.clips
                    .get(clip_idx as usize)
                    .ok_or_else(|| RasterError(format!("bad clip index {clip_idx}")))?,
            )
        };
        if clipmode != CLIPMODE_NONE && clip.is_none() {
            return err(format!(
                "op {op}: clipmode {clipmode} requires a clip index"
            ));
        }

        // --- resolve geometry into jobs ---------------------------------
        let mut jobs: Vec<Job> = Vec::new();
        match op {
            OP_POLY_FILL | OP_POLY_OUTLINE => {
                if n < 3 {
                    return err(format!("op {op}: polygon needs at least 3 points, got {n}"));
                }
                let pts = apply_xform(payload, xform.map(|x| &x.m));
                let pts = match clipmode {
                    CLIPMODE_NONE => Some(pts),
                    CLIPMODE_GEOM => {
                        let clip = clip.unwrap();
                        let clipped = geom::clip_polygon(&pts, &clip.hps);
                        // Matches render.py's `if len(clipped) >= 3` guard:
                        // fully clipped prims silently vanish.
                        if clipped.len() < 3 {
                            None
                        } else {
                            Some(clipped)
                        }
                    }
                    CLIPMODE_GATE => {
                        let clip = clip.unwrap();
                        if point_in_poly(pts[0].x, pts[0].y, &clip.pts) {
                            Some(pts)
                        } else {
                            None
                        }
                    }
                    _ => return err(format!("op {op}: unsupported clipmode {clipmode}")),
                };
                if let Some(pts) = pts {
                    jobs.push(if op == OP_POLY_FILL {
                        Job::PolyFill(pts)
                    } else {
                        Job::PolyOutline(pts, width)
                    });
                }
            }
            OP_POLYLINE => {
                if n < 2 {
                    return err(format!("polyline needs at least 2 points, got {n}"));
                }
                let mut pts = apply_xform(payload, xform.map(|x| &x.m));
                if closed {
                    // render.py: `spts = spts + [spts[0]]`, then clip; the
                    // closed ring is drawn as an open polyline.
                    pts.push(pts[0]);
                }
                match clipmode {
                    CLIPMODE_NONE => jobs.push(Job::Polyline(pts, width)),
                    CLIPMODE_GEOM => {
                        let clip = clip.unwrap();
                        for piece in geom::clip_polyline_halfplanes(&pts, &clip.hps) {
                            if piece.len() >= 2 {
                                jobs.push(Job::Polyline(piece, width));
                            }
                        }
                    }
                    CLIPMODE_GATE => {
                        let clip = clip.unwrap();
                        if point_in_poly(pts[0].x, pts[0].y, &clip.pts) {
                            jobs.push(Job::Polyline(pts, width));
                        }
                    }
                    _ => return err(format!("polyline: unsupported clipmode {clipmode}")),
                }
            }
            OP_CIRCLE_FILL | OP_CIRCLE_OUTLINE => {
                if n != 0 {
                    return err(format!("op {op}: N must be 0, got {n}"));
                }
                if op == OP_CIRCLE_OUTLINE && width != 1 {
                    // Phase 1 never draws a width>1 circle outline (pygame's
                    // moiré-hole territory); keep the door shut.
                    return err(format!("circle outline width must be 1, got {width}"));
                }
                let (cx, cy) = apply_xform_pt(payload[0], payload[1], xform.map(|x| &x.m));
                let mut r = payload[2] as f64;
                if radius_scaled {
                    let x = xform
                        .ok_or_else(|| RasterError("RADIUS_SCALED requires an xform".into()))?;
                    r *= x.scale;
                }
                let r = c_int(r); // pg_IntFromObj float truncation
                let keep = match clipmode {
                    CLIPMODE_NONE => true,
                    CLIPMODE_GATE => point_in_poly(cx, cy, &clip.unwrap().pts),
                    _ => return err(format!("op {op}: unsupported clipmode {clipmode}")),
                };
                if keep {
                    jobs.push(if op == OP_CIRCLE_FILL {
                        Job::CircleFill { cx, cy, r }
                    } else {
                        Job::CircleThin { cx, cy, r }
                    });
                }
            }
            OP_RECT_FILL | OP_RECT_OUTLINE => {
                if n != 0 {
                    return err(format!("op {op}: N must be 0, got {n}"));
                }
                if xform.is_some() {
                    return err("rect ops are screen-space; xform not supported");
                }
                let (x, y) = (payload[0] as f64, payload[1] as f64);
                let (w, h) = (payload[2] as f64, payload[3] as f64);
                let keep = match clipmode {
                    CLIPMODE_NONE => true,
                    CLIPMODE_GATE => point_in_poly(x + w / 2.0, y + h / 2.0, &clip.unwrap().pts),
                    _ => return err(format!("op {op}: unsupported clipmode {clipmode}")),
                };
                if keep {
                    let width = if op == OP_RECT_FILL { 0 } else { width.max(1) };
                    jobs.push(Job::Rect { x, y, w, h, width });
                }
            }
            OP_CLIP_FILL => {
                if n != 0 {
                    return err(format!("clip fill: N must be 0, got {n}"));
                }
                if xform.is_some() {
                    return err("clip fill: the clip polygon is already screen-space; xform not supported");
                }
                if clipmode != CLIPMODE_NONE {
                    return err(format!(
                        "clip fill: clipmode must be NONE (fills the clip entry itself), got {clipmode}"
                    ));
                }
                let clip =
                    clip.ok_or_else(|| RasterError("clip fill requires a clip index".into()))?;
                jobs.push(Job::PolyFill(clip.pts.clone()));
            }
            OP_TEX_FILL => {
                if n != 0 {
                    return err(format!("tex fill: N must be 0, got {n}"));
                }
                if clipmode != CLIPMODE_NONE {
                    return err(format!(
                        "tex fill: clipmode must be NONE (fills the clip entry itself), got {clipmode}"
                    ));
                }
                let clip =
                    clip.ok_or_else(|| RasterError("tex fill requires a clip index".into()))?;
                let xform =
                    xform.ok_or_else(|| RasterError("tex fill requires an xform index".into()))?;
                if !xform.m.is_invertible() {
                    return err("tex fill: instance xform is not invertible");
                }
                let bbox_min = v(payload[0] as f64, payload[1] as f64);
                jobs.push(Job::TexFill {
                    pts: clip.pts.clone(),
                    inv: xform.m.inverse(),
                    bbox_min,
                    tex_id: rgba_u32,
                });
            }
            OP_GLOW => {
                if layer != LAYER_OVERLAY {
                    return err("glow must be on the overlay layer");
                }
                if n != 0 {
                    return err(format!("glow: N must be 0, got {n}"));
                }
                let (cx, cy) = apply_xform_pt(payload[0], payload[1], xform.map(|x| &x.m));
                let mut r = payload[2] as f64;
                if radius_scaled {
                    let x = xform
                        .ok_or_else(|| RasterError("RADIUS_SCALED requires an xform".into()))?;
                    r *= x.scale;
                }
                // Glow blits are always bbox-clipped in render.py; GATE
                // additionally drops the glow when its center is outside the
                // clip polygon (screenglow registration). BBOX draws
                // unconditionally (muzzle flashes / bolt glows).
                let clip = clip.ok_or_else(|| RasterError("glow requires a clip index".into()))?;
                let keep = match clipmode {
                    CLIPMODE_BBOX => true,
                    CLIPMODE_GATE => point_in_poly(cx, cy, &clip.pts),
                    _ => return err(format!("glow: unsupported clipmode {clipmode}")),
                };
                if keep {
                    jobs.push(Job::Glow {
                        cx,
                        cy,
                        r,
                        rect: clip.bbox,
                    });
                }
            }
            _ => unreachable!("opcode validated in exec_stream"),
        }

        // --- route to a layer -------------------------------------------
        match layer {
            LAYER_WORLD => {
                for job in &jobs {
                    if let Job::TexFill { pts, inv, bbox_min, tex_id } = job {
                        let tex = self.textures.get(tex_id).ok_or_else(|| {
                            RasterError(format!("tex fill: unknown texture id {tex_id}"))
                        })?;
                        let (xs, ys) = round_pts(pts);
                        tex_fill_poly(&mut self.world, self.w, self.h, &xs, &ys, tex, *inv, *bbox_min);
                    } else {
                        run_job(&mut self.world, self.w, self.h, PxWrite::Set(rgba), job);
                    }
                }
            }
            LAYER_ENTITY => {
                for job in &jobs {
                    run_job(&mut self.entity, self.w, self.h, PxWrite::Set(rgba), job);
                }
            }
            LAYER_OVERLAY => {
                for job in jobs {
                    self.overlay.push(OverlayJob { job, rgba });
                }
            }
            _ => unreachable!("layer validated above"),
        }
        Ok(())
    }

    /// Composite (idempotently since the last `begin`) and borrow the
    /// straight (non-premultiplied) RGBA8 frame. The Python binding copies
    /// out of this slice without an intermediate allocation.
    pub fn compose_frame(&mut self) -> &[u8] {
        self.compose();
        &self.world
    }

    /// Composite and write the RGBA8 frame into `out` (len must be w*h*4).
    pub fn finish_into(&mut self, out: &mut [u8]) -> Result<(), RasterError> {
        let want = self.world.len();
        if out.len() != want {
            return err(format!(
                "output buffer is {} bytes, need {want} (w*h*4)",
                out.len()
            ));
        }
        out.copy_from_slice(self.compose_frame());
        Ok(())
    }

    /// Composite and return the RGBA8 frame.
    pub fn finish(&mut self) -> Vec<u8> {
        self.compose_frame().to_vec()
    }

    fn compose(&mut self) {
        if self.composed {
            return;
        }
        self.composed = true;
        // (3) lightmap multiply on the WORLD plane ONLY: (c*m + 255) >> 8,
        // BLEND_RGB_MULT parity. Runs BEFORE the entity fold so entities
        // are never darkened by it -- zero ambient for world geometry,
        // entities stay the always-visible sensor-trace layer.
        if self.darkness_on {
            for (px, m) in self
                .world
                .chunks_exact_mut(4)
                .zip(self.lightmap.chunks_exact(3))
            {
                for ch in 0..3 {
                    px[ch] = ((px[ch] as u32 * m[ch] as u32 + 255) >> 8) as u8;
                }
            }
        }

        // (4) coverage fold + alpha-over. Both planes hold binary alpha, so
        // min() then over is a per-pixel select — bit-exact vs pygame's
        // BLEND_RGBA_MIN + straight blit.
        for (i, (px, &cov)) in self
            .entity
            .chunks_exact(4)
            .zip(self.coverage.iter())
            .enumerate()
        {
            if px[3].min(cov) == 255 {
                self.world[i * 4..i * 4 + 3].copy_from_slice(&px[..3]);
            }
        }

        // (5) overlay replay in submission order.
        let overlay = std::mem::take(&mut self.overlay);
        for oj in &overlay {
            let px = match oj.job {
                Job::Glow { .. } => PxWrite::Add([oj.rgba[0], oj.rgba[1], oj.rgba[2]]),
                _ => PxWrite::Set(oj.rgba),
            };
            run_job(&mut self.world, self.w, self.h, px, &oj.job);
        }
    }
}

/// Transform a flat f32 payload into screen-space f64 points.
fn apply_xform(payload: &[f32], m: Option<&Mat3>) -> Vec<Vec2> {
    payload
        .chunks_exact(2)
        .map(|p| {
            let pt = v(p[0] as f64, p[1] as f64);
            match m {
                Some(m) => m.apply(pt),
                None => pt,
            }
        })
        .collect()
}

fn apply_xform_pt(x: f32, y: f32, m: Option<&Mat3>) -> (f64, f64) {
    let pt = v(x as f64, y as f64);
    let pt = match m {
        Some(m) => m.apply(pt),
        None => pt,
    };
    (pt.x, pt.y)
}

/// Round a screen-space point list to pixel int lists (`_pts` parity).
fn round_pts(pts: &[Vec2]) -> (Vec<i32>, Vec<i32>) {
    let mut xs = Vec::with_capacity(pts.len());
    let mut ys = Vec::with_capacity(pts.len());
    for p in pts {
        xs.push(py_round(p.x));
        ys.push(py_round(p.y));
    }
    (xs, ys)
}

fn unpack_rgba(c: u32) -> [u8; 4] {
    [(c >> 24) as u8, (c >> 16) as u8, (c >> 8) as u8, c as u8]
}

fn run_job(buf: &mut [u8], w: i32, h: i32, px: PxWrite, job: &Job) {
    let full = IRect { x: 0, y: 0, w, h };
    let clip = match job {
        // pygame surf.set_clip(rect) clamps the rect to the surface.
        Job::Glow { rect, .. } => rect.intersect(full),
        _ => full,
    };
    if clip.is_empty() {
        return;
    }
    let mut c = Canvas {
        buf,
        bpp: 4,
        w,
        clip,
        px,
    };
    match job {
        Job::PolyFill(pts) => {
            let (xs, ys) = round_pts(pts);
            pg_poly_fill(&mut c, &xs, &ys);
        }
        Job::PolyOutline(pts, width) => {
            let (xs, ys) = round_pts(pts);
            pg_poly_outline(&mut c, &xs, &ys, *width);
        }
        Job::Polyline(pts, width) => {
            let (xs, ys) = round_pts(pts);
            pg_polyline(&mut c, &xs, &ys, *width);
        }
        Job::CircleFill { cx, cy, r } => {
            pg_circle_filled(&mut c, py_round(*cx), py_round(*cy), *r);
        }
        Job::CircleThin { cx, cy, r } => {
            pg_circle_thin(&mut c, py_round(*cx), py_round(*cy), *r);
        }
        Job::Rect { x, y, w, h, width } => {
            pg_rect(&mut c, c_int(*x), c_int(*y), c_int(*w), c_int(*h), *width);
        }
        Job::Glow { cx, cy, r, .. } => {
            glow_radial(&mut c, *cx, *cy, *r);
        }
        Job::TexFill { .. } => {
            unreachable!("TexFill is routed specially in exec_cmd's LAYER_WORLD arm")
        }
    }
}

/// Analytic radial glow: for each pixel with dist <= r, add peak * a^2 with
/// a = 1 - dist/r — the exact per-pixel formula render.py `_bake_glows`
/// premultiplies into its sprites (math.hypot, int() truncation), applied
/// with BLEND_RGB_ADD saturation. Radii <= 1 draw nothing (`_blit_glow`).
fn glow_radial(c: &mut Canvas, cx: f64, cy: f64, r: f64) {
    if r <= 1.0 {
        return;
    }
    let peak = match c.px {
        PxWrite::Add(p) => p,
        _ => unreachable!("glow always draws additively"),
    };
    let x0 = c.clip.x.max((cx - r).floor() as i32 - 1);
    let x1 = (c.clip.x + c.clip.w - 1).min((cx + r).ceil() as i32 + 1);
    let y0 = c.clip.y.max((cy - r).floor() as i32 - 1);
    let y1 = (c.clip.y + c.clip.h - 1).min((cy + r).ceil() as i32 + 1);
    for py in y0..=y1 {
        for px in x0..=x1 {
            let dist = (px as f64 - cx).hypot(py as f64 - cy);
            if dist <= r {
                let a = 1.0 - dist / r;
                let aa = a * a;
                let add = [
                    (peak[0] as f64 * aa) as u8,
                    (peak[1] as f64 * aa) as u8,
                    (peak[2] as f64 * aa) as u8,
                ];
                let saved = c.px;
                c.px = PxWrite::Add(add);
                c.write(px, py);
                c.px = saved;
            }
        }
    }
}

