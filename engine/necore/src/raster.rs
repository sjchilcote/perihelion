    fn cmd(
        op: u32,
        flags: u32,
        clip: u32,
        xform: u32,
        rgba: u32,
        pts: &[f64],
    ) -> (Vec<u32>, Vec<f32>) {
        let n = match op {
            OP_POLY_FILL | OP_POLY_OUTLINE | OP_POLYLINE => (pts.len() / 2) as u32,
            _ => 0,
        };
        (
            vec![op, flags, clip, xform, rgba, n],
            pts.iter().map(|&p| p as f32).collect(),
        )
    }

