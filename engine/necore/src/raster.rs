/// `draw_line`: thin Bresenham with per-pixel clip checks (pygame does not
/// geometrically pre-clip thin lines). `err = (dx>dy?dx:-dy)/2` relies on
/// C's truncation division, which `i32 /` matches.
fn pg_line_thin(c: &mut Canvas, mut x1: i32, mut y1: i32, x2: i32, y2: i32) {
    if x1 == x2 && y1 == y2 {
        c.set_at(x1, y1);
        return;
    }
    if y1 == y2 {
        let step = if x1 < x2 { 1 } else { -1 };
        for i in 0..=(x1 - x2).abs() {
            c.set_at(x1 + step * i, y1);
        }
        return;
    }
    if x1 == x2 {
        let step = if y1 < y2 { 1 } else { -1 };
        for i in 0..=(y1 - y2).abs() {
            c.set_at(x1, y1 + step * i);
        }
        return;
    }
    let dx = (x2 - x1).abs();
    let sx = if x1 < x2 { 1 } else { -1 };
    let dy = (y2 - y1).abs();
    let sy = if y1 < y2 { 1 } else { -1 };
    let mut e = (if dx > dy { dx } else { -dy }) / 2;
    while x1 != x2 || y1 != y2 {
        c.set_at(x1, y1);
        let e2 = e;
        if e2 > -dx {
            e -= dy;
            x1 += sx;
        }
        if e2 < dy {
            e += dx;
            y1 += sy;
        }
    }
    c.set_at(x2, y2);
}

/// `clip_line`: trivial-reject only (coords are never modified).
fn pg_clip_line_reject(
    c: &Canvas,
    x1: i32,
    y1: i32,
    x2: i32,
    y2: i32,
    width: i32,
    xinc: bool,
) -> bool {
    let (left, right, top, bottom) = if xinc {
        (
            x1.min(x2) - width,
            x1.max(x2) + width,
            y1.min(y2),
            y1.max(y2),
        )
    } else {
        (
            x1.min(x2),
            x1.max(x2),
            y1.min(y2) - width,
            y1.max(y2) + width,
        )
    };
    !(c.clip.x > right
        || c.clip.y > bottom
        || c.clip.x + c.clip.w <= left
        || c.clip.y + c.clip.h <= top)
}

/// `draw_line_width`: width > 1 lines are `width` pixels of perpendicular
/// strip stacked along the Bresenham walk — flat butt ends, no joins, and
/// an asymmetric extra pixel for even widths. NOT a capped rectangle.
fn pg_line_width(c: &mut Canvas, mut x1: i32, mut y1: i32, x2: i32, y2: i32, width: i32) {
    if width < 1 {
        return;
    }
    if width == 1 {
        pg_line_thin(c, x1, y1, x2, y2);
        return;
    }
    let end_x = c.clip.x + c.clip.w - 1;
    let end_y = c.clip.y + c.clip.h - 1;
    let extra_width = 1 - (width % 2);
    let width = width / 2;

    // Decide which direction to grow (width/thickness).
    let xinc = (x1 - x2).abs() <= (y1 - y2).abs();

    if !pg_clip_line_reject(c, x1, y1, x2, y2, width, xinc) {
        return;
    }

    if x1 == x2 && y1 == y2 {
        // Single point.
        let start = (x1 - width + extra_width).max(c.clip.x);
        let end = end_x.min(x1 + width);
        if start <= end {
            c.hline_raw(start, y1, end);
        }
        return;
    }

    let dx = (x2 - x1).abs();
    let dy = (y2 - y1).abs();
    let sx = if x2 > x1 { 1 } else { -1 };
    let sy = if y2 > y1 { 1 } else { -1 };
    let mut e = (if dx > dy { dx } else { -dy }) / 2;
    if xinc {
        while y1 != y2 + sy {
            if c.clip.y <= y1 && y1 <= end_y {
                let start = (x1 - width + extra_width).max(c.clip.x);
                let end = end_x.min(x1 + width);
                if start <= end {
                    c.hline_raw(start, y1, end);
                }
            }
            let e2 = e;
            if e2 > -dx {
                e -= dy;
                x1 += sx;
            }
            if e2 < dy {
                e += dx;
                y1 += sy;
            }
        }
    } else {
        while x1 != x2 + sx {
            if c.clip.x <= x1 && x1 <= end_x {
                let start = (y1 - width + extra_width).max(c.clip.y);
                let end = end_y.min(y1 + width);
                if start <= end {
                    for y in start..=end {
                        c.write(x1, y);
                    }
                }
            }
            let e2 = e;
            if e2 > -dx {
                e -= dy;
                x1 += sx;
            }
            if e2 < dy {
                e += dx;
                y1 += sy;
            }
        }
    }
}

/// `draw_filltri`: pygame fills 3-point polygons with this f32-slope
/// scanline, NOT with `draw_fillpoly` — the two produce different pixels,
/// so the dispatch on point count must be preserved.
fn pg_filltri(c: &mut Canvas, xs: &[i32], ys: &[i32]) {
    let (mut p0x, mut p0y) = (xs[0], ys[0]);
    let (mut p1x, mut p1y) = (xs[1], ys[1]);
    let (mut p2x, mut p2y) = (xs[2], ys[2]);

    if p1y < p0y {
        std::mem::swap(&mut p1x, &mut p0x);
        std::mem::swap(&mut p1y, &mut p0y);
    }
    if p2y < p1y {
        std::mem::swap(&mut p1x, &mut p2x);
        std::mem::swap(&mut p1y, &mut p2y);
        if p1y < p0y {
            std::mem::swap(&mut p1x, &mut p0x);
            std::mem::swap(&mut p1y, &mut p0y);
        }
    }
    if p0y == p1y && p1y == p2y && p0x == p1x && p1x != p2x {
        std::mem::swap(&mut p1x, &mut p2x);
        std::mem::swap(&mut p1y, &mut p2y);
    }

    let d1 = ((p2x - p0x) as f64 / ((p2y - p0y) as f64 + 1e-17)) as f32;
    let d2 = ((p1x - p0x) as f64 / ((p1y - p0y) as f64 + 1e-17)) as f32;
    let d3 = ((p2x - p1x) as f64 / ((p2y - p1y) as f64 + 1e-17)) as f32;
    for y in p0y..=p2y {
        let x1 = p0x + ((y - p0y) as f32 * d1) as i32;
        let x2 = if y < p1y {
            p0x + ((y - p0y) as f32 * d2) as i32
        } else {
            p1x + ((y - p1y) as f32 * d3) as i32
        };
        c.hline_clip(x1, y, x2);
    }
}

/// `draw_fillpoly`: even-odd scanline fill. Intersections are computed in
/// f32 and alternately floor/ceil'd by running parity *in edge order* (not
/// sorted order) — a pygame quirk that shifts span ends by a pixel on some
/// slopes; keep it. Horizontal bottom/interior edges get a second pass.
fn pg_fillpoly(c: &mut Canvas, xs: &[i32], ys: &[i32]) {
    let n = xs.len();
    let mut miny = ys[0];
    let mut maxy = ys[0];
    for &yy in ys.iter() {
        miny = miny.min(yy);
        maxy = maxy.max(yy);
    }

    if miny == maxy {
        // Special case: polygon only 1 pixel high.
        let mut minx = xs[0];
        let mut maxx = xs[0];
        for &xx in xs.iter() {
            minx = minx.min(xx);
            maxx = maxx.max(xx);
        }
        c.hline_clip(minx, miny, maxx);
        return;
    }

    let mut xsect: Vec<i32> = Vec::with_capacity(n);
    for y in miny..=maxy {
        xsect.clear();
        for i in 0..n {
            let ip = if i == 0 { n - 1 } else { i - 1 };
            let (y1, y2, x1, x2) = if ys[ip] < ys[i] {
                (ys[ip], ys[i], xs[ip], xs[i])
            } else if ys[ip] > ys[i] {
                (ys[i], ys[ip], xs[i], xs[ip])
            } else {
                continue; // horizontal: handled below
            };
            if (y >= y1 && y < y2) || (y == maxy && y2 == maxy) {
                // C: int product, then int/float division in f32.
                let num = (y - y1) as i64 * (x2 - x1) as i64;
                let mut intersect = num as f32 / (y2 - y1) as f32;
                if xsect.len() % 2 == 0 {
                    intersect = intersect.floor();
                } else {
                    intersect = intersect.ceil();
                }
                xsect.push(intersect as i32 + x1);
            }
        }
        xsect.sort_unstable();
        let mut i = 0;
        while i + 1 < xsect.len() {
            c.hline_clip(xsect[i], y, xsect[i + 1]);
            i += 2;
        }
    }

    // Horizontal border lines interior to the y-range.
    for i in 0..n {
        let ip = if i == 0 { n - 1 } else { i - 1 };
        let y = ys[i];
        if miny < y && ys[ip] == y && y < maxy {
            c.hline_clip(xs[i], y, xs[ip]);
        }
    }
}

/// `polygon(width=0)` fill dispatch: exactly 3 points goes to the triangle
/// filler, anything else to the general scanline filler.
fn pg_poly_fill(c: &mut Canvas, xs: &[i32], ys: &[i32]) {
    if xs.len() == 3 {
        pg_filltri(c, xs, ys);
    } else {
        pg_fillpoly(c, xs, ys);
    }
}

/// `(y, x1, x2)` spans of `pg_filltri`, verbatim, for callers that need
/// per-pixel access (texture sampling) instead of a constant-color hline.
/// Kept as an exact duplicate of `pg_filltri`'s math (not a refactor of it)
/// so the pygame-parity fixtures for the constant-fill path stay untouched.
fn filltri_spans(xs: &[i32], ys: &[i32]) -> Vec<(i32, i32, i32)> {
    let (mut p0x, mut p0y) = (xs[0], ys[0]);
    let (mut p1x, mut p1y) = (xs[1], ys[1]);
    let (mut p2x, mut p2y) = (xs[2], ys[2]);

    if p1y < p0y {
        std::mem::swap(&mut p1x, &mut p0x);
        std::mem::swap(&mut p1y, &mut p0y);
    }
    if p2y < p1y {
        std::mem::swap(&mut p1x, &mut p2x);
        std::mem::swap(&mut p1y, &mut p2y);
        if p1y < p0y {
            std::mem::swap(&mut p1x, &mut p0x);
            std::mem::swap(&mut p1y, &mut p0y);
        }
    }
    if p0y == p1y && p1y == p2y && p0x == p1x && p1x != p2x {
        std::mem::swap(&mut p1x, &mut p2x);
        std::mem::swap(&mut p1y, &mut p2y);
    }

    let d1 = ((p2x - p0x) as f64 / ((p2y - p0y) as f64 + 1e-17)) as f32;
    let d2 = ((p1x - p0x) as f64 / ((p1y - p0y) as f64 + 1e-17)) as f32;
    let d3 = ((p2x - p1x) as f64 / ((p2y - p1y) as f64 + 1e-17)) as f32;
    let mut out = Vec::with_capacity((p2y - p0y).max(0) as usize + 1);
    for y in p0y..=p2y {
        let x1 = p0x + ((y - p0y) as f32 * d1) as i32;
        let x2 = if y < p1y {
            p0x + ((y - p0y) as f32 * d2) as i32
        } else {
            p1x + ((y - p1y) as f32 * d3) as i32
        };
        out.push((y, x1, x2));
    }
    out
}

/// `(y, x1, x2)` spans of `pg_fillpoly`, verbatim (see `filltri_spans`).
fn fillpoly_spans(xs: &[i32], ys: &[i32]) -> Vec<(i32, i32, i32)> {
    let n = xs.len();
    let mut miny = ys[0];
    let mut maxy = ys[0];
    for &yy in ys.iter() {
        miny = miny.min(yy);
        maxy = maxy.max(yy);
    }

    let mut out = Vec::new();
    if miny == maxy {
        let mut minx = xs[0];
        let mut maxx = xs[0];
        for &xx in xs.iter() {
            minx = minx.min(xx);
            maxx = maxx.max(xx);
        }
        out.push((miny, minx, maxx));
        return out;
    }

    let mut xsect: Vec<i32> = Vec::with_capacity(n);
    for y in miny..=maxy {
        xsect.clear();
        for i in 0..n {
            let ip = if i == 0 { n - 1 } else { i - 1 };
            let (y1, y2, x1, x2) = if ys[ip] < ys[i] {
                (ys[ip], ys[i], xs[ip], xs[i])
            } else if ys[ip] > ys[i] {
                (ys[i], ys[ip], xs[i], xs[ip])
            } else {
                continue;
            };
            if (y >= y1 && y < y2) || (y == maxy && y2 == maxy) {
                let num = (y - y1) as i64 * (x2 - x1) as i64;
                let mut intersect = num as f32 / (y2 - y1) as f32;
                if xsect.len() % 2 == 0 {
                    intersect = intersect.floor();
                } else {
                    intersect = intersect.ceil();
                }
                xsect.push(intersect as i32 + x1);
            }
        }
        xsect.sort_unstable();
        let mut i = 0;
        while i + 1 < xsect.len() {
            out.push((y, xsect[i], xsect[i + 1]));
            i += 2;
        }
    }

    for i in 0..n {
        let ip = if i == 0 { n - 1 } else { i - 1 };
        let y = ys[i];
        if miny < y && ys[ip] == y && y < maxy {
            out.push((y, xs[i], xs[ip]));
        }
    }
    out
}

/// `poly_fill_spans` == `pg_poly_fill`'s dispatch, span form.
fn poly_fill_spans(xs: &[i32], ys: &[i32]) -> Vec<(i32, i32, i32)> {
    if xs.len() == 3 {
        filltri_spans(xs, ys)
    } else {
        fillpoly_spans(xs, ys)
    }
}

/// `drawhorzlineclipbounding` order+clamp, span-only (no canvas write).
fn clamp_span(mut a: i32, mut b: i32, clip: IRect) -> Option<(i32, i32)> {
    if b < a {
        std::mem::swap(&mut a, &mut b);
    }
    a = a.max(clip.x);
    b = b.min(clip.x + clip.w - 1);
    if b < clip.x || a >= clip.x + clip.w {
        None
    } else {
        Some((a, b))
    }
}

/// `polygon(width>0)` == `lines(closed=1)`: every ring edge is an
/// independent thick line (no joins).
fn pg_poly_outline(c: &mut Canvas, xs: &[i32], ys: &[i32], width: i32) {
    if width < 1 {
        return;
    }
    let n = xs.len();
    for i in 1..n {
        pg_line_width(c, xs[i - 1], ys[i - 1], xs[i], ys[i], width);
    }
    if n > 2 {
        pg_line_width(c, xs[n - 1], ys[n - 1], xs[0], ys[0], width);
    }
}

/// `lines(closed=0)`: consecutive independent segments.
fn pg_polyline(c: &mut Canvas, xs: &[i32], ys: &[i32], width: i32) {
    if width < 1 {
        return;
    }
    for i in 1..xs.len() {
        pg_line_width(c, xs[i - 1], ys[i - 1], xs[i], ys[i], width);
    }
}

/// `circle()` front-door checks shared by fill/outline: zero-area radius and
/// the center-farther-than-radius-outside-the-clip trivial reject.
fn pg_circle_reject(c: &Canvas, x0: i32, y0: i32, radius: i32) -> bool {
    radius < 1
        || x0 > c.clip.x + c.clip.w + radius
        || x0 < c.clip.x - radius
        || y0 > c.clip.y + c.clip.h + radius
        || y0 < c.clip.y - radius
}

/// `draw_circle_filled`: midpoint circle emitting spans; note the `f >= 0`
/// gating of the wide spans and the `2r+1`-ish asymmetric footprint.
fn pg_circle_filled(c: &mut Canvas, x0: i32, y0: i32, radius: i32) {
    if pg_circle_reject(c, x0, y0, radius) {
        return;
    }
    let mut f = 1 - radius;
    let mut ddf_x = 0;
    let mut ddf_y = -2 * radius;
    let mut x = 0;
    let mut y = radius;
    // Overflow guard from the C source; inert for sane coordinates.
    let xmax: i64 = if x0 < 0 {
        x0 as i64 + i32::MAX as i64 + 1
    } else {
        i32::MAX as i64 - x0 as i64
    };

    while x < y {
        if f >= 0 {
            y -= 1;
            ddf_y += 2;
            f += ddf_y;
        }
        x += 1;
        ddf_x += 2;
        f += ddf_x + 1;

        if f >= 0 {
            let e = x0 + ((x - 1) as i64).min(xmax) as i32;
            c.hline_clip(x0 - x, y0 + y - 1, e);
            c.hline_clip(x0 - x, y0 - y, e);
        }
        let e = x0 + ((y - 1) as i64).min(xmax) as i32;
        c.hline_clip(x0 - y, y0 + x - 1, e);
        c.hline_clip(x0 - y, y0 - x, e);
    }
}

/// `draw_circle_bresenham_thin` (width == 1 outline): 8-octant plot with the
/// `-1` offsets that give pygame circles their quadrant asymmetry.
fn pg_circle_thin(c: &mut Canvas, x0: i32, y0: i32, radius: i32) {
    if pg_circle_reject(c, x0, y0, radius) {
        return;
    }
    let mut f = 1 - radius;
    let mut ddf_x = 0;
    let mut ddf_y = -2 * radius;
    let mut x = 0;
    let mut y = radius;
    while x < y {
        if f >= 0 {
            y -= 1;
            ddf_y += 2;
            f += ddf_y;
        }
        x += 1;
        ddf_x += 2;
        f += ddf_x + 1;

        c.set_at(x0 + x - 1, y0 + y - 1);
        c.set_at(x0 - x, y0 + y - 1);
        c.set_at(x0 + x - 1, y0 - y);
        c.set_at(x0 - x, y0 - y);
        c.set_at(x0 + y - 1, y0 + x - 1);
        c.set_at(x0 + y - 1, y0 - x);
        c.set_at(x0 - y, y0 + x - 1);
        c.set_at(x0 - y, y0 - x);
    }
}

/// `draw.rect`: width==0 is an SDL_FillRect of the clipped rect; width>0
/// draws hline/vline borders — unless the *clipped* rect is too thin, in
/// which case pygame silently falls back to a fill.
fn pg_rect(c: &mut Canvas, x: i32, y: i32, w: i32, h: i32, width: i32) {
    let clipped = IRect { x, y, w, h }.intersect(c.clip);
    if clipped.is_empty() {
        return;
    }
    if width > 0 && width * 2 < clipped.w && width * 2 < clipped.h {
        // draw_rect(x1, y1, x2, y2, width)
        let (x1, y1, x2, y2) = (x, y, x + w - 1, y + h - 1);
        for i in 0..width {
            c.hline_clip(x1, y1 + i, x2);
            c.hline_clip(x1, y2 - i, x2);
        }
        for i in 0..(y2 - y1) - 2 * width + 1 {
            c.hline_clip(x1, y1 + width + i, x1 + width - 1);
            c.hline_clip(x2 - width + 1, y1 + width + i, x2);
        }
    } else {
        for yy in clipped.y..clipped.y + clipped.h {
            c.hline_raw(clipped.x, yy, clipped.x + clipped.w - 1);
        }
    }
}

