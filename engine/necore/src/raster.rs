/// Command-stream or argument error. Every malformed stream fails loudly —
/// no prim is ever silently skipped for structural reasons.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct RasterError(pub String);

impl std::fmt::Display for RasterError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(&self.0)
    }
}

impl std::error::Error for RasterError {}

fn err<T>(msg: impl Into<String>) -> Result<T, RasterError> {
    Err(RasterError(msg.into()))
}

