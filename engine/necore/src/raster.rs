    /// the set of lit pixels.
    fn lit_pixels(w: usize, h: usize, op: u32, flags: u32, pts: &[f64]) -> Vec<(i32, i32)> {
        let mut r = Raster::new(w, h);
        r.set_darkness(false);
        r.begin(0x0000_00FF);
        draw_one(&mut r, op, flags, IDX_NONE, IDX_NONE, WHITE, pts);
        let buf = r.finish();
        let mut out = Vec::new();
        for y in 0..h {
            for x in 0..w {
                let off = (y * w + x) * 4;
                if buf[off] != 0 || buf[off + 1] != 0 || buf[off + 2] != 0 {
                    out.push((x as i32, y as i32));
                }
            }
        }
        out
    }

