"""Regenerate chants_data.py from the fetched GregoBase GABC files.

    uv run python tools/musicgen/build_chant_data.py

GABC stays in the scratchpad; the extracted event data (public-domain
chant, transcription provenance in each entry) is committed.
"""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from gabc import parse  # noqa: E402

S = Path("/tmp/claude-1000/-home-login-PycharmProjects-"
         "noneuclideantopdownshooter/6f0b5b45-ac47-4526-b96e-c9dc90e4fe0b"
         "/scratchpad/musicgen")

# id -> (python name, why it's in the menu)
MENU = {
    3973: ("MEDIA_VITA",
           "'In the midst of life we are in death' — battle antiphon, "
           "mode 4 (Phrygian)"),
    14065: ("LIBERA_ME",
            "Office of the Dead responsory, mode 1"),
    7978: ("REQUIEM_INTROIT",
           "Requiem aeternam introit, mode 6 (Graduale Romanum 1974)"),
    19728: ("VEXILLA_REGIS",
            "'The banners of the King advance' — processional battle "
            "hymn, mode 1"),
    8686: ("VENI_CREATOR",
           "Invocation of the spirit — boot-up litany register, mode 8"),
    8670: ("PANGE_LINGUA",
           "Aquinas corpus hymn, mode 3 (Phrygian family)"),
    1745: ("VIDERUNT_OMNES",
           "Gradual, mode 5 — the Perotin organum tenor; stretch for "
           "machine-organum treatment"),
}

MAX_STEPS = 16 * 16          # cap an excerpt at 16 bars of 16th-steps


def excerpt(events):
    """Opening period: cut at the first long rest at/after 8 bars, hard
    cap at 16 bars; always end on a rest boundary."""
    out, steps = [], 0
    for p, d in events:
        out.append((p, d))
        steps += d
        if p is None and d >= 8 and steps >= 8 * 16:
            break
        if steps >= MAX_STEPS:
            if out[-1][0] is not None:
                out.append((None, 4))
            break
    return out


def main():
    lines = [
        '"""Chant menu data — GENERATED by build_chant_data.py. DATA ONLY.',
        "",
        "Each entry: [(semitones_from_final, dur_16th_steps) | (None, rest)],",
        "same convention as chants.DIES_IRAE_STROPHE. Sources: GregoBase",
        "GABC (public-domain chant); id + book in each block.",
        '"""',
        "",
    ]
    names = []
    for gid, (name, why) in MENU.items():
        text = (S / f"gabc/{gid}.gabc").read_text()
        ev, meta = parse(text)
        ex = excerpt(ev)
        total = sum(d for _, d in ex)
        lines.append(f"# {meta.get('name', '?')} — {why}")
        lines.append(f"# GregoBase id {gid}; book: {meta.get('book', '?')};"
                     f" mode {meta.get('mode', '?')};"
                     f" {len(ex)} events, {total/16:.1f} bars")
        lines.append(f"{name} = [")
        row = "    "
        for e in ex:
            tok = f"{e!r}, "
            if len(row) + len(tok) > 76:
                lines.append(row.rstrip())
                row = "    "
            row += tok
        lines.append(row.rstrip())
        lines.append("]")
        lines.append("")
        names.append(name)
    lines.append("CHANT_MENU = {")
    for n in names:
        lines.append(f'    "{n.lower()}": {n},')
    lines.append("}")
    lines.append("")
    out = Path(__file__).parent / "chants_data.py"
    out.write_text("\n".join(lines))
    print(f"wrote {out} ({len(names)} chants)")
    for n in names:
        print(" ", n)


if __name__ == "__main__":
    main()
