"""tools/dialogue/assemble_regen3578.py

Assembles the final regenerated Scene 3/5/7/8 prose from the raw Hermes
candidates in tools/dialogue/candidates/regen_scene{3,5,7,8}_run1.json
(generated by regen_scenes3578.py under the comprehension-gate pass), and
logs a difflib similarity ratio for every shipped line-block against its
raw source block (must be >= 0.85 -- confirms shipped text is Hermes
verbatim, not rewritten).

Selection rationale (this run):
  - Scene 3: run1 cand 0 (T=0.7) whole, EXCEPT the <<ELSEIF
    flag:compounded_bluff>> catch block, swapped from cand 3 (T=0.95):
    cand 0's version said the asset was "stolen from the Testators" -- a
    faction inversion (his scene-0 claim was about his own Church's
    cargo; the Testators are the station's builders). Cand 3's block is
    clean and cites the LHX serial prefix, satisfying the continuity
    requirement that scene 3 cite scene 1's stated serial.
  - Scene 5: run1 cand 0 (T=0.7) whole. Only candidate whose MISSION
    choice states the disputed category in plain words on the page
    (cand 2's "You know the doctrine" hides the dispute from a blind
    reader entirely), with concrete Mirror Ward / records-stack anchors,
    and without cand 3's continuity error ("You called me an apostate in
    the Mirror Ward" -- the word was used at the scene-0 terminal).
  - Scene 7: run1 cand 1 (T=0.8) whole, EXCEPT the trust-demeanor opening
    gate, swapped from cand 2 (T=0.9): cand 1's three tone branches were
    near-identical ("Commando, I have the report." / "Commando. I have
    the report."), a tone dial rather than a tone gate. Cand 2's are
    genuinely distinct in register. Cand 1 wins the body for its terse
    grief beats ("No." / "What happened to them.") and its concrete Fold
    callback, against cand 2's one ornamental Commando line ("This is
    the only one that was ever real"), which fails the say-the-thing law.
  - Scene 8: run1 cand 1 (T=0.8) whole, EXCEPT the
    <<IF flag:claimed_doctrinal_finding>> quiet-catch block, swapped from
    cand 0 (T=0.7): cand 1's block reads "Your doctrinal claim from
    scene 4" -- an out-of-world meta leak. Cand 1 wins the body because
    its ELSE (offer-not-reached) branch is the only one that grounds the
    vessel concretely for a cold reader ("A sealed cryogenic preservation
    vessel. The station grew around it. What I am reading is its
    life-support telemetry. That is the container we came to find.") --
    the exact establishing requirement this regen exists to satisfy;
    cand 3's ELSE branch is two lines and cand 2 misplaces the Tesseract
    Deck's geometry onto the Core.

Mechanical normalizations (fixed bookkeeping, not prose -- same policy as
assemble_regen.py's CHOICE-header normalization):
  - ">> CHOICE:" -> ">> CHOICE (stance labels mandatory):".
  - Scene 7: "<<ELSEIF trust>=3>>" -> "<<ELSEIF trust>=2>>" (the shipped
    gate fix -- trust>=3 is unreachable; see DIALOGUE_SCRIPT.md
    "Gate fixes applied this pass" item 1).
  - Scene 8: "<<IF trust>=4>>" -> "<<IF trust>=0>>" (shipped gate fix
    item 2 -- trust>=4 unreachable by any of the 6,561 paths).
  - Scene 7 mission-branch doctrine line and Scene 8
    claimed_doctrinal_finding line: append "  -> catch_effects: trust-2"
    (shipped gate fix items 3/4 -- the double-weight quiet catches the
    brief mandates; annotation only, no text changed).
  - Scene 3 cand 1-style "COMMANDO:" prefixes inside choice lines: not
    present in the selected candidates; no normalization needed.
  - Trailing "---" markers stripped (the master script supplies its own
    scene separators).

Run:
    uv run python tools/dialogue/assemble_regen3578.py
"""
from __future__ import annotations

import difflib
import json
import re
from pathlib import Path

TOOL_DIR = Path(__file__).resolve().parent
CAND = TOOL_DIR / "candidates"


def load(scene: int, idx: int) -> str:
    d = json.loads((CAND / f"regen_scene{scene}_run1.json").read_text())
    for c in d["candidates"]:
        if c["candidate"] == idx:
            return c["text"]
    raise KeyError(f"scene {scene} candidate {idx} not found")


def ratio(a: str, b: str) -> float:
    return difflib.SequenceMatcher(None, a.strip(), b.strip()).ratio()


def block_between(text: str, start_token: str, end_tokens: list[str]) -> str:
    """Extract lines strictly after the line containing start_token, up to
    (exclusive) the first subsequent line starting with any of end_tokens."""
    lines = text.splitlines()
    i = next(n for n, l in enumerate(lines) if start_token in l)
    out = []
    for l in lines[i + 1:]:
        if any(l.strip().startswith(t) for t in end_tokens):
            break
        out.append(l)
    return "\n".join(out).strip("\n")


def normalize(text: str) -> str:
    text = text.replace(">> CHOICE:", ">> CHOICE (stance labels mandatory):")
    text = "\n".join(l for l in text.splitlines() if l.strip() != "---")
    return text.strip()


def main() -> None:
    log = {"blocks": []}

    def logblock(name: str, shipped: str, raw: str) -> None:
        log["blocks"].append({"block": name, "similarity": round(ratio(shipped, raw), 4)})

    # ---- Scene 3: cand 0 frame + cand 3's compounded_bluff block ---------
    s3_c0 = load(3, 0)
    s3_c3 = load(3, 3)
    c0_elseif = block_between(s3_c0, "<<ELSEIF flag:compounded_bluff>>", ["<<ELSE>>"])
    c3_elseif = block_between(s3_c3, "<<ELSEIF flag:compounded_bluff>>", ["<<ELSE>>"])
    scene3 = s3_c0.replace(c0_elseif, c3_elseif)
    scene3 = normalize(scene3)
    logblock("scene3.frame (run1 cand0)", scene3.replace(c3_elseif, c0_elseif), s3_c0)
    logblock("scene3.compounded_bluff (donor: run1 cand3)", c3_elseif, c3_elseif)

    # ---- Scene 5: cand 0 whole -------------------------------------------
    s5_c0 = load(5, 0)
    scene5 = normalize(s5_c0)
    logblock("scene5.whole (run1 cand0)", scene5, s5_c0)

    # ---- Scene 7: cand 1 frame + cand 2's trust tone gate ----------------
    s7_c1 = load(7, 1)
    s7_c2 = load(7, 2)
    c1_gate = block_between(s7_c1, "<<IF trust<=-3>>", ["<<IF flag:asked_about_salvage>>"])
    c2_gate = block_between(s7_c2, "<<IF trust<=-3>>", ["<<IF flag:asked_about_salvage>>"])
    # both extracted blocks end with <<END>> of the tone gate; keep it.
    scene7 = s7_c1.replace(c1_gate, c2_gate)
    scene7 = scene7.replace("<<ELSEIF trust>=3>>", "<<ELSEIF trust>=2>>")
    scene7 = scene7.replace(
        "RATIO: My records contain no Church doctrine authorizing recovery under these conditions.",
        "RATIO: My records contain no Church doctrine authorizing recovery under these conditions.  -> catch_effects: trust-2",
    )
    scene7 = normalize(scene7)
    logblock("scene7.frame (run1 cand1)", scene7.replace(c2_gate, c1_gate), s7_c1)
    logblock("scene7.tone_gate (donor: run1 cand2)", c2_gate, c2_gate)

    # ---- Scene 8: cand 1 frame + cand 0's doctrinal-catch block ----------
    s8_c1 = load(8, 1)
    s8_c0 = load(8, 0)
    c1_doct = block_between(s8_c1, "<<IF flag:claimed_doctrinal_finding>>", ["<<END>>"])
    c0_doct = block_between(s8_c0, "<<IF flag:claimed_doctrinal_finding>>", ["<<END>>"])
    scene8 = s8_c1.replace(c1_doct, c0_doct)
    scene8 = scene8.replace("<<IF trust>=4>>", "<<IF trust>=0>>")
    scene8 = scene8.replace(
        "RATIO: I have cross-referenced your doctrinal claim against all available Church records. There is no match.",
        "RATIO: I have cross-referenced your doctrinal claim against all available Church records. There is no match.  -> catch_effects: trust-2",
    )
    scene8 = normalize(scene8)
    logblock("scene8.frame (run1 cand1)", scene8.replace(c0_doct, c1_doct), s8_c1)
    logblock("scene8.doctrinal_catch (donor: run1 cand0)", c0_doct, c0_doct)

    # sanity: mechanical annotations present
    for name, text, needles in [
        ("scene3", scene3, ["-> catch_effects: trust-1", "sets: confessed_bluff",
                             "sets: doubled_down_after_catch", "sets: called_her_hypocrite", "LHX"]),
        ("scene5", scene5, ["sets: asked_her_belief", "sets: claimed_doctrinal_finding",
                             "sets: accused_dehumanization"]),
        ("scene7", scene7, ["<<ELSEIF trust>=2>>", "sets: requested_reanalysis",
                             "sets: mission_overrides_verdict", "sets: blamed_ratio_for_failure",
                             "catch_effects: trust-2"]),
        ("scene8", scene8, ["<<IF trust>=0>>", "sets: disclosure_accepted", "sets: disclosure_hedged",
                             "sets: disclosure_refused", "catch_effects: trust-2"]),
    ]:
        for needle in needles:
            assert needle in text, f"{name}: missing {needle!r}"

    out = {
        "scene3_final": scene3,
        "scene5_final": scene5,
        "scene7_final": scene7,
        "scene8_final": scene8,
        "similarity_log": log["blocks"],
    }
    out_path = CAND / "regen3578_final_assembled.json"
    out_path.write_text(json.dumps(out, indent=2))
    print(json.dumps(log, indent=2))
    print(f"\nwrote {out_path}")


if __name__ == "__main__":
    main()
